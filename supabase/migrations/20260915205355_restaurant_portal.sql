-- Chowseek multi-tenant restaurant portal.
-- This migration is intentionally designed for the existing Chowseek Supabase project.
-- Existing sponsored_results rows are preserved under a Legacy / Unassigned restaurant
-- until a platform admin assigns them to a restaurant.

create schema if not exists chowseek_private;

create table if not exists public.restaurants (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 200),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  address text,
  description text,
  website text,
  phone text,
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  active boolean not null default true,
  plan_key text not null default 'free',
  max_users integer not null default 2 check (max_users >= 1),
  max_placements integer not null default 3 check (max_placements >= 0),
  feature_flags jsonb not null default '{}'::jsonb,
  stripe_customer_id text unique,
  stripe_subscription_id text unique,
  subscription_status text,
  subscription_price_id text,
  current_period_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.restaurant_memberships (
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('owner','editor','viewer')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (restaurant_id, user_id)
);

create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Carry forward anyone already authorized by the legacy sponsorship portal.
insert into public.platform_admins (user_id)
select user_id from chowseek_private.portal_admins
on conflict (user_id) do nothing;

create table if not exists public.portal_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  restaurant_id uuid references public.restaurants(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Separate from Chowseek's existing consumer stripe_webhook_events table.
create table if not exists public.restaurant_stripe_events (
  event_id text primary key,
  event_type text not null,
  processed_at timestamptz not null default now()
);

alter table public.sponsored_results
  add column if not exists restaurant_id uuid references public.restaurants(id) on delete restrict;

