-- Admin detection: users can only read their own admin marker.
drop policy if exists "users read own platform admin marker" on public.platform_admins;
create policy "users read own platform admin marker"
on public.platform_admins for select to authenticated
using (user_id = (select auth.uid()));

-- Restaurants.
drop policy if exists "restaurant members read restaurants" on public.restaurants;
create policy "restaurant members read restaurants"
on public.restaurants for select to authenticated
using (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(id));

drop policy if exists "restaurant editors update profile" on public.restaurants;
create policy "restaurant editors update profile"
on public.restaurants for update to authenticated
using (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(id, array['owner','editor']))
with check (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(id, array['owner','editor']));

drop policy if exists "platform admins create restaurants" on public.restaurants;
create policy "platform admins create restaurants"
on public.restaurants for insert to authenticated
with check (chowseek_private.is_platform_admin());

drop policy if exists "platform admins delete restaurants" on public.restaurants;
create policy "platform admins delete restaurants"
on public.restaurants for delete to authenticated
using (chowseek_private.is_platform_admin());

-- Memberships are readable by the member or platform admins. All writes are trusted-server only.
drop policy if exists "members read memberships" on public.restaurant_memberships;
create policy "members read memberships"
on public.restaurant_memberships for select to authenticated
using (user_id = (select auth.uid()) or chowseek_private.is_platform_admin());

-- Sponsored placements.
drop policy if exists "restaurant users read placements" on public.sponsored_results;
create policy "restaurant users read placements"
on public.sponsored_results for select to authenticated
using (
  chowseek_private.is_platform_admin()
  or (restaurant_id is not null and chowseek_private.has_restaurant_role(restaurant_id))
);

drop policy if exists "restaurant editors create placements" on public.sponsored_results;
create policy "restaurant editors create placements"
on public.sponsored_results for insert to authenticated
with check (
  restaurant_id is not null
  and (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(restaurant_id, array['owner','editor']))
);

drop policy if exists "restaurant editors update placements" on public.sponsored_results;
create policy "restaurant editors update placements"
on public.sponsored_results for update to authenticated
using (
  restaurant_id is not null
  and (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(restaurant_id, array['owner','editor']))
)
with check (
  restaurant_id is not null
  and (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(restaurant_id, array['owner','editor']))
);

drop policy if exists "restaurant editors delete unused placements" on public.sponsored_results;
create policy "restaurant editors delete unused placements"
on public.sponsored_results for delete to authenticated
using (
  coalesce(impression_count,0) = 0
  and restaurant_id is not null
  and (chowseek_private.is_platform_admin() or chowseek_private.has_restaurant_role(restaurant_id, array['owner','editor']))
);

-- Audit log is visible to platform admins, plus restaurant owners for their own restaurant.
drop policy if exists "authorized users read audit log" on public.portal_audit_log;
create policy "authorized users read audit log"
on public.portal_audit_log for select to authenticated
using (
  chowseek_private.is_platform_admin()
  or (restaurant_id is not null and chowseek_private.has_restaurant_role(restaurant_id, array['owner']))
);

