create index if not exists sponsored_results_restaurant_id_idx on public.sponsored_results(restaurant_id);
create index if not exists restaurant_memberships_user_id_idx on public.restaurant_memberships(user_id) where active;
create index if not exists portal_audit_log_restaurant_created_idx on public.portal_audit_log(restaurant_id, created_at desc);

create or replace function chowseek_private.is_platform_admin(p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_user_id is not null and exists (
    select 1 from public.platform_admins pa where pa.user_id = p_user_id
  );
$$;

create or replace function chowseek_private.has_restaurant_role(
  p_restaurant_id uuid,
  p_roles text[] default array['owner','editor','viewer']::text[],
  p_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_user_id is not null and exists (
    select 1
    from public.restaurant_memberships rm
    where rm.restaurant_id = p_restaurant_id
      and rm.user_id = p_user_id
      and rm.active
      and rm.role = any(p_roles)
  );
$$;

revoke all on function chowseek_private.is_platform_admin(uuid) from public;
revoke all on function chowseek_private.has_restaurant_role(uuid,text[],uuid) from public;
grant usage on schema chowseek_private to authenticated;
grant execute on function chowseek_private.is_platform_admin(uuid) to authenticated;
grant execute on function chowseek_private.has_restaurant_role(uuid,text[],uuid) to authenticated;

create or replace function chowseek_private.enforce_membership_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_limit integer; v_count integer;
begin
  if new.active and (tg_op = 'INSERT' or old.active is distinct from true or old.restaurant_id is distinct from new.restaurant_id) then
    select max_users into v_limit from public.restaurants where id = new.restaurant_id for update;
    select count(*) into v_count
    from public.restaurant_memberships
    where restaurant_id = new.restaurant_id and active and user_id <> new.user_id;
    if v_count >= v_limit then
      raise exception 'Restaurant user limit reached (%).', v_limit using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;

create or replace function chowseek_private.enforce_placement_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_limit integer; v_count integer;
begin
  if new.restaurant_id is null then return new; end if;
  if tg_op = 'INSERT' or old.restaurant_id is distinct from new.restaurant_id then
    select max_placements into v_limit from public.restaurants where id = new.restaurant_id for update;
    select count(*) into v_count
    from public.sponsored_results
    where restaurant_id = new.restaurant_id and (tg_op = 'INSERT' or id <> new.id);
    if v_count >= v_limit then
      raise exception 'Restaurant placement limit reached (%).', v_limit using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_membership_limit on public.restaurant_memberships;
create trigger enforce_membership_limit
before insert or update of restaurant_id, active on public.restaurant_memberships
for each row execute function chowseek_private.enforce_membership_limit();

drop trigger if exists enforce_placement_limit on public.sponsored_results;
create trigger enforce_placement_limit
before insert or update of restaurant_id on public.sponsored_results
for each row execute function chowseek_private.enforce_placement_limit();

create or replace function chowseek_private.audit_portal_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare payload jsonb; rid uuid; tid text;
begin
  payload := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  rid := case
    when tg_table_name = 'restaurants' and tg_op = 'DELETE' then null
    when tg_table_name = 'restaurants' then (payload->>'id')::uuid
    else nullif(payload->>'restaurant_id','')::uuid
  end;
  tid := coalesce(payload->>'id', payload->>'user_id');
  insert into public.portal_audit_log(actor_user_id, restaurant_id, action, target_type, target_id, details)
  values (auth.uid(), rid, lower(tg_op), tg_table_name, tid, jsonb_build_object('row', payload));
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

